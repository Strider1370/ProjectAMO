export function operatorCode(registration) {
  if (!registration) return ''
  return REGISTRATION_OPERATOR[String(registration).toUpperCase()] || ''
}

// Operator code only when we actually have a logo image for it (else '').
export function operatorLogoId(registration) {
  const code = operatorCode(registration)
  return OPERATOR_LOGOS.has(code) ? code : ''
}

export function operatorLogoFile(code) {
  return `${code}.png`
}
