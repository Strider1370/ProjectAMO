test('my-map 그룹 보완: 긴 목록 드래그 자동 스크롤·접힌 그룹 펼침·외부 드롭 무변경', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop', '데스크톱 그룹 드래그 계약')
  test.setTimeout(90000)
  await startMap(page, '긴 그룹 검증')
  for (const name of ['A', 'B']) {
    await page.getByRole('textbox', { name: '새 그룹 이름', exact: true }).fill(name)
    await page.getByRole('button', { name: '그룹 추가', exact: true }).click()
  }
  await page.getByRole('button', { name: '좌표 여러 줄 입력', exact: true }).click()
  const bulk = page.getByRole('region', { name: '좌표 여러 줄 입력', exact: true })
  await bulk.getByRole('combobox', { name: '대상 그룹' }).selectOption({ label: 'A' })
  await bulk.locator('textarea').fill(Array.from({ length: 30 }, (_, i) => `지점${i}\t37.${i}\t127`).join('\n'))
  await bulk.getByRole('button', { name: '점 30개 추가', exact: true }).click()
  const item = page.locator('.my-map-editor-item').first()
  // 고정 패널 헤더 뒤에서 시작하면 native dragstart가 안 날 수 있다. 실제 항목을
  // 스크롤 영역 중앙에 놓고 시작을 관찰해야 자동 스크롤 자체를 검증할 수 있다.
  await item.evaluate((element) => element.scrollIntoView({ block: 'center' }))
  const grip = await item.locator('.my-map-editor-grip').boundingBox()
  const panel = page.locator('.my-map-panel-content')
  const bounds = await panel.boundingBox(), before = await panel.evaluate((element) => element.scrollTop)
  await page.evaluate(() => { window.__myMapFirstDragStarts = 0; window.addEventListener('dragstart', () => { window.__myMapFirstDragStarts += 1 }, { once: true }) })
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2)
  await page.mouse.down()
  await page.mouse.move(grip.x + grip.width / 2 + 15, grip.y + grip.height / 2 + 10, { steps: 5 })
  await expect.poll(() => page.evaluate(() => window.__myMapFirstDragStarts)).toBe(1)
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height - 10, { steps: 12 })
  await expect.poll(() => panel.evaluate((element) => element.scrollTop)).toBeGreaterThan(before + 150)
  await page.mouse.move(800, 350, { steps: 5 }); await page.mouse.up()
  const stoppedAt = await panel.evaluate((element) => element.scrollTop)
  await page.evaluate(() => new Promise((resolve) => { let frames = 0; const tick = () => ++frames === 15 ? resolve() : requestAnimationFrame(tick); requestAnimationFrame(tick) }))
  expect(await panel.evaluate((element) => element.scrollTop)).toBe(stoppedAt)
  expect((await saved(page, '긴 그룹 검증')).items).toHaveLength(30)
  // Keep the source away from the fixed panel header before starting the second drag.
  await page.getByRole('button', { name: 'B 접기', exact: true }).click()
  await item.evaluate((element) => element.scrollIntoView({ block: 'center' }))
  await page.evaluate(() => { window.__myMapDragStarts = 0; window.addEventListener('dragstart', () => { window.__myMapDragStarts += 1 }) })
  const source = await item.locator('.my-map-editor-grip').boundingBox()
  await page.mouse.move(source.x + 8, source.y + 8); await page.mouse.down()
  await page.mouse.move(source.x + 23, source.y + 18, { steps: 5 })
  await expect.poll(() => page.evaluate(() => window.__myMapDragStarts)).toBe(1)
  const destination = page.getByRole('button', { name: 'B 0', exact: true })
  await destination.scrollIntoViewIfNeeded()
  const target = await destination.boundingBox()
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 10 })
  await page.mouse.move(target.x + target.width / 2 + 1, target.y + target.height / 2)
  await expect(page.getByRole('button', { name: 'B 접기', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await page.mouse.up()
  await expect(page.getByRole('button', { name: 'B 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '되돌리기', exact: true }).click()
  await expect(page.getByRole('button', { name: 'B 0', exact: true })).toBeVisible()
})
