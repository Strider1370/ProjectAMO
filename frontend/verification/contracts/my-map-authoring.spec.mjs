async function startMap(page, name) {
  await page.addInitScript((version) => { localStorage.setItem('amo.tour.v1.done', 'true'); localStorage.setItem('projectamo:lastSeenVersion', version) }, CURRENT_VERSION)
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: '내 지도', exact: true }).click()
  await page.getByRole('button', { name: '새 지도', exact: true }).click()
  await page.getByRole('textbox', { name: '지도 이름', exact: true }).fill(name)
  await page.getByRole('button', { name: '만들기', exact: true }).click()
  await page.waitForFunction(() => window.__map?.getLayer('my-map-edit-line'))
  await page.evaluate(() => window.__map.jumpTo({ center: [127, 37], zoom: 8 }))
}
const features = (page, source = 'my-map-src') => page.evaluate((id) => window.__map?.getSource(id)?.serialize().data.features ?? [], source)
const preview = async (page) => (await features(page, 'my-map-edit-preview')).find((feature) => feature.properties.role === 'shape')?.geometry
const click = (page, x, y) => page.locator('.mapboxgl-canvas').click({ position: { x, y } })
async function drag(page, from, to) {
  const box = await page.locator('.mapboxgl-canvas').boundingBox()
  await page.mouse.move(box.x + from.x, box.y + from.y); await page.mouse.down()
  await page.mouse.move(box.x + to.x, box.y + to.y, { steps: 8 }); await page.mouse.up()
}
async function handle(page, role, index = 0) {
  await expect.poll(() => page.evaluate(({ role, index }) => window.__map.queryRenderedFeatures({ layers: ['my-map-edit-vertex', 'my-map-edit-midpoint'] }).some((f) => f.properties.role === role && Number(f.properties.index ?? 0) === index), { role, index })).toBe(true)
  return page.evaluate(({ role, index }) => {
    const feature = window.__map.getSource('my-map-edit-preview').serialize().data.features.find((f) => f.properties.role === role && Number(f.properties.index ?? 0) === index)
    return window.__map.project(feature.geometry.coordinates)
  }, { role, index })
}
async function saved(page, name) {
  return page.evaluate(async (name) => {
    const db = await new Promise((resolve) => { const r = indexedDB.open('projectamo-my-map-account-v1'); r.onsuccess = () => resolve(r.result) })
    const rows = await new Promise((resolve) => { const r = db.transaction('completed').objectStore('completed').getAll(); r.onsuccess = () => resolve(r.result) })
    db.close(); return rows.map((row) => row.document.document ?? row.document).find((document) => document.name === name) ?? null
  }, name)
}

