import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const frontend = fileURLToPath(new URL('../', import.meta.url))
const packageRoot = path.join(frontend, 'node_modules/pretendard-gov')
const sourcePath = path.join(packageRoot, 'dist/web/static/pretendard-gov-dynamic-subset.css')
const outputPath = path.join(frontend, 'src/shared/theme/pretendard-gov.generated.css')
const licensePath = path.join(frontend, 'public/licenses/pretendard-gov-OFL-1.1.txt')
const weights = [400, 500, 600, 700, 800, 900]
const check = process.argv.includes('--check')

// Read the installed, lockfile-pinned distribution. Never subset by app text:
// user names, uploaded documents and notices can introduce any supported glyph.
const { version } = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8'))
assert.equal(version, '1.3.9', 'Review the upstream font distribution before updating its version')
const source = fs.readFileSync(sourcePath, 'utf8')
const faces = source.match(/@font-face\s*\{[^}]*\}/g)
assert.equal(faces?.length, 1080, 'Unexpected upstream font-face structure')
const weightOf = face => Number(face.match(/font-weight:\s*(\d+);/)?.[1])
const rangeOf = face => face.match(/unicode-range:\s*([^;]+);/)?.[1]
const referenceRanges = faces.filter(face => weightOf(face) === 400).map(rangeOf)
assert.equal(referenceRanges.length, 120)
assert.ok(referenceRanges.every(Boolean))

const generated = []
for (const weight of weights) {
  const selected = faces.filter(face => weightOf(face) === weight)
  assert.deepEqual(selected.map(rangeOf), referenceRanges, `Character coverage changed for weight ${weight}`)
  for (const face of selected) {
    assert.match(face, /font-family:\s*'Pretendard GOV';/)
    assert.match(face, /font-style:\s*normal;/)
    assert.match(face, /font-display:\s*swap;/)
    const woff2 = face.match(/src:\s*url\((\.\/woff2-dynamic-subset\/[^)]+\.woff2)\) format\('woff2'\),\s*url\([^)]*\.woff\) format\('woff'\);/)
    assert.ok(woff2, 'Unexpected source formats: review instead of silently dropping a font')
    const asset = path.resolve(path.dirname(sourcePath), woff2[1])
    assert.equal(fs.readFileSync(asset).subarray(0, 4).toString(), 'wOF2', `Invalid font: ${asset}`)
    const relative = path.relative(path.dirname(outputPath), asset).split(path.sep).join('/')
    generated.push(face.replace(woff2[0], `src: url('${relative}') format('woff2');`))
  }
}

const header = `/* Generated by npm run fonts:generate from pretendard-gov ${version}.
 * Keep all 120 Unicode ranges for weights ${weights.join(', ')}.
 * Do not edit by hand. License: /licenses/pretendard-gov-OFL-1.1.txt.
 */\n`
const copyright = source.slice(0, source.indexOf('/* [0] */'))
const outputs = [
  [outputPath, header + copyright + generated.join('\n') + '\n'],
  [licensePath, fs.readFileSync(path.join(packageRoot, 'dist/LICENSE.txt'), 'utf8')],
]
for (const [target, content] of outputs) {
  if (check) {
    assert.equal(fs.readFileSync(target, 'utf8'), content, `${path.basename(target)} is stale; run npm run fonts:generate`)
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, content)
  }
}
console.log(`Fonts ${check ? 'verified' : 'generated'}: ${generated.length} woff2 faces, all character ranges preserved`)
