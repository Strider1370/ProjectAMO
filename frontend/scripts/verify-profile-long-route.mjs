import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import AxeBuilder from '@axe-core/playwright'
import { ROUTES, waypointLabels } from '../src/features/vertical-profile-concept/routeNavigation.js'

// Every waypoint must remain eligible when selected, including the dense cluster.
for (const index of [0, 1, 160, 200, 239, 399, 400]) {
  const labels = waypointLabels(ROUTES.long.waypoints, [0, 6000], 72, 1100, index)
  assert.ok(labels.some(p => p.index === index))
  for (let i = 1; i < labels.length; i++) assert.ok(labels[i].labelX - labels[i - 1].labelX >= labels[i].half + labels[i - 1].half + 8)
}
const browser = await chromium.launch()
const errors = []
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } })
  const page = await context.newPage()
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:5173/concepts/vertical-profile?demo=1')
  const route = page.getByRole('combobox', { name: '시안 항로' })
  await route.waitFor()
  assert.equal(await route.inputValue(), 'long')
  const overview = page.getByRole('slider', { name: '확대 구간 이동' })
  const readRange = () => overview.getAttribute('aria-valuetext')
  const labels = page.locator('.vpc-waypoint')
  assert.ok(await labels.count() < 30)
  const checkLabels = async () => {
    const boxes = await labels.evaluateAll(nodes => nodes.map(n => { const b = n.getBoundingClientRect(); return { left:b.left, right:b.right } }).sort((a,b)=>a.left-b.left))
    for(let i=1;i<boxes.length;i++) assert.ok(boxes[i].left > boxes[i-1].right, JSON.stringify(boxes))
  }
  await checkLabels()
  const wheelPlot = await page.locator('.vpc-plot-target').boundingBox()
  const wheelX = wheelPlot.x + wheelPlot.width * .7
  await page.mouse.move(wheelX, wheelPlot.y + wheelPlot.height * .6)
  const scrollBefore = await page.evaluate(() => window.scrollY)
  await page.mouse.wheel(0, -160)
  await page.waitForFunction(() => Number(document.querySelector('.vpc-overview-track').getAttribute('aria-valuemax')) > 0)
  const start = Number(await overview.getAttribute('aria-valuenow'))
  const span = 6000 - Number(await overview.getAttribute('aria-valuemax'))
  assert.ok(Math.abs(start + .7 * span - 4200) < 2, 'wheel anchor stays under pointer')
  assert.equal(await page.evaluate(() => window.scrollY), scrollBefore)
  await page.mouse.wheel(0, 160)
  await page.waitForFunction(() => document.querySelector('.vpc-overview-track').getAttribute('aria-disabled') === 'true')
  // Repeated events hit the minimum without exceeding route bounds.
  await page.locator('.vpc-chart').evaluate((el, coords) => {
    for (let i = 0; i < 20; i++) el.dispatchEvent(new WheelEvent('wheel', { clientX:coords.x, clientY:coords.y, deltaY:-240, bubbles:true, cancelable:true }))
  }, { x: wheelX, y: wheelPlot.y + wheelPlot.height * .6 })
  assert.ok(Math.abs(6000 - Number(await overview.getAttribute('aria-valuemax')) - 45) < .001)
  await page.getByRole('button', { name:'전체 항로 맞춤' }).click()
  const axis = page.locator('.vpc-waypoint-target')
  await axis.focus(); await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight')
  assert.equal(await page.locator('.vpc-waypoint.is-selected').textContent(), 'W0001')
  await checkLabels()
  await page.screenshot({ path: 'artifacts/vertical-profile-concept/long-route-overview.png' })
  for (let i=0;i<5;i++) await page.getByRole('button',{name:'차트 확대',exact:true}).click()
  assert.ok(await labels.count() > 8)
  const plot = page.locator('.vpc-plot-target')
  const b = await plot.boundingBox()
  const axisBefore = await page.locator('.vpc-axis-label').first().boundingBox()
  const readoutBefore = await page.locator('.vpc-readout').textContent()
  await page.mouse.move(b.x+b.width*.75,b.y+b.height*.7); await page.mouse.down()
  await page.mouse.move(b.x+b.width*.4,b.y+b.height*.7,{steps:12}); await page.mouse.up()
  assert.ok(Number(await overview.getAttribute('aria-valuenow')) > 0)
  assert.equal(await page.locator('.vpc-readout').textContent(), readoutBefore, 'pan must not pick a point')
  assert.deepEqual(await page.locator('.vpc-axis-label').first().boundingBox(),axisBefore)
  const beforeOverview=await readRange()
  const track=await overview.boundingBox()
  await page.mouse.click(track.x+track.width*.43,track.y+track.height/2)
  assert.notEqual(await readRange(),beforeOverview)
  await checkLabels()
  await axis.focus(); await page.keyboard.press('ArrowRight')
  assert.equal(await page.locator('.vpc-waypoint.is-selected').textContent(),'W0002')
  await overview.focus(); await page.keyboard.press('End')
  assert.match(await readRange(),/6000 NM/)
  await axis.focus(); await page.keyboard.press('End')
  assert.equal(await page.locator('.vpc-waypoint.is-selected').textContent(),'ARR')
  await checkLabels()
  await overview.focus(); await page.keyboard.press('Home')
  assert.equal(await overview.getAttribute('aria-valuenow'),'0')
  // Dense cluster: labels must stay disjoint at a different viewport range.
  await page.mouse.click(track.x+track.width*.42,track.y+track.height/2)
  await checkLabels()
  await page.screenshot({path:'artifacts/vertical-profile-concept/long-route-zoom.png'})
  const a11y=await new AxeBuilder({page}).include('.vpc-overlay').analyze()
  assert.deepEqual(a11y.violations.filter(v=>['serious','critical'].includes(v.impact)).map(v=>v.id),[])
  await route.selectOption('short'); assert.match(await readRange(),/312 NM/)
  await route.selectOption('long'); assert.match(await readRange(),/6000 NM/)
  await page.close()
  const mobile = await browser.newPage({viewport:{width:390,height:844},hasTouch:true})
  mobile.on('pageerror',e=>errors.push(e.message))
  await mobile.goto('http://127.0.0.1:5173/concepts/vertical-profile?demo=1')
  await mobile.getByRole('combobox',{name:'시안 항로'}).waitFor()
  const chart = await mobile.locator('.vpc-chart').evaluate(e=>({height:e.clientHeight,svg:e.querySelector('svg').getBoundingClientRect().height}))
  assert.ok(chart.height>=chart.svg-1,JSON.stringify(chart))
  await mobile.getByRole('button',{name:'차트 확대',exact:true}).tap()
  const target=mobile.locator('.vpc-plot-target')
  const box=await target.boundingBox()
  const client=await mobile.context().newCDPSession(mobile)
  await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+box.width*.8,y:box.y+box.height*.7}]})
  await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:box.x+box.width*.4,y:box.y+box.height*.7}]})
  await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  assert.ok(Number(await mobile.getByRole('slider',{name:'확대 구간 이동'}).getAttribute('aria-valuenow'))>0)
  await mobile.locator('.vpc-waypoint-target').tap()
  assert.equal(await mobile.locator('.vpc-waypoint.is-selected').count(),1)
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await mobile.screenshot({path:'artifacts/vertical-profile-concept/long-route-mobile.png'})
  assert.deepEqual(errors,[])
  console.log('PASS: 401 waypoints, collision-free/priority labels, zoom, fixed-axis mouse/touch pan, overview, keyboard selection, boundaries, route switch, mobile, accessibility')
} finally { await browser.close() }
